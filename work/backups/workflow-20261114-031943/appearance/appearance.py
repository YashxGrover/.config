#!/usr/bin/env python3
"""Shared palette controls. No third-party shell files are executed."""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent
CONFIG = ROOT.parent
PALETTES = ROOT / 'palettes.json'
STATE = ROOT / 'state.json'
BACKUP = ROOT / 'originals'
KD = '/opt/homebrew/bin/kiwidesk'
SB = '/opt/homebrew/bin/sketchybar'

def run(argv):
    result = subprocess.run(argv, text=True, capture_output=True, timeout=30)
    if result.returncode or 'cannot connect' in result.stdout.lower() or result.stdout.startswith('error:'):
        raise RuntimeError(result.stderr.strip() or result.stdout.strip() or str(argv))
    return result.stdout.strip()

def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(text)
    tmp.replace(path)

def state():
    return json.loads(STATE.read_text()) if STATE.exists() else {}

def choose(prompt, options):
    script = '''on run argv
set answer to choose from list (items 2 thru -1 of argv) with prompt (item 1 of argv)
if answer is false then return ""
return item 1 of answer
end run'''
    return run(['/usr/bin/osascript', '-e', script, prompt] + options)

def apply(name, accent=None):
    palettes = json.loads(PALETTES.read_text())
    p = palettes[name].copy()
    if accent:
        if not re.fullmatch(r'#[0-9a-fA-F]{6}', accent):
            raise ValueError('Accent must be #RRGGBB')
        p['accent'] = accent
    for relative in ['sketchybar/colors.sh', 'kitty/current-theme.conf']:
        original = CONFIG / relative
        backup = BACKUP / relative
        if original.exists() and not backup.exists():
            backup.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(original, backup)
    roles = dict(BAR=('b0',p['bg']), PILL=('df',p['surface']),
                 PILL_BORDER=('ff',p['muted']), POPUP_BG=('f2',p['bg']),
                 BG=('ff',p['bg']), BG1=('ff',p['surface']), BG2=('ff',p['muted']),
                 FG=('ff',p['fg']), DIM=('ff',p['muted']))
    for role,key in [('RED','red'),('GREEN','green'),('YELLOW','yellow'),
                     ('BLUE','blue'),('PURPLE','purple'),('AQUA','aqua'),('ORANGE','accent')]:
        roles[role] = ('ff',p[key])
    write(CONFIG/'sketchybar/colors.sh', '# Generated by appearance/appearance.py\n' +
          '\n'.join('{}=0x{}{}'.format(k,a,c[1:]) for k,(a,c) in roles.items())+'\n')
    lines = ['# Shared appearance: '+name, 'background '+p['bg'], 'foreground '+p['fg'],
             'cursor '+p['accent'], 'selection_background '+p['purple'],
             'selection_foreground '+p['bg'], 'active_tab_background '+p['accent'],
             'active_tab_foreground '+p['bg'], 'inactive_tab_background '+p['surface'],
             'inactive_tab_foreground '+p['muted']]
    ansi = [p[k] for k in ['surface','red','green','yellow','blue','purple','aqua','fg']]
    lines += ['color{} {}'.format(i,c) for i,c in enumerate(ansi+ansi)]
    write(CONFIG/'kitty/current-theme.conf', '\n'.join(lines)+'\n')
    s = state(); s.update(theme=name, accent=p['accent']); write(STATE,json.dumps(s,indent=2)+'\n')
    errors=[]
    for command,color in [('border.set_focused_color',p['accent']),
                          ('border.set_unfocused_color',p['muted']+'40'),
                          ('pocket.set_color',p['accent']),
                          ('space_bar.set_focused_item_color',p['accent']),
                          ('space_bar.set_focused_highlight_color',p['accent']),
                          ('kiwishelf.set_fill_color',p['bg']+'E8'),
                          ('kiwishelf.set_item_color',p['fg']),
                          ('kiwishelf.set_active_item_color',p['accent'])]:
        try: run([KD,command,color])
        except RuntimeError as e: errors.append(str(e))
    try: run([SB,'--reload'])
    except RuntimeError as e: errors.append(str(e))
    print('Palette written: '+name+'. Kitty uses it in new windows. Successful KiwiDesk updates remain live until kept.')
    for error in errors: print('Live update unavailable: '+error,file=sys.stderr)

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('action',choices=['menu','list','apply','accent','wallpaper','restore','keep'])
    parser.add_argument('theme',nargs='?')
    args=parser.parse_args()
    if args.action=='list':
        print('\n'.join(json.loads(PALETTES.read_text()))); return
    if args.action=='apply': apply(args.theme); return
    if args.action=='restore':
        for relative in ['sketchybar/colors.sh','kitty/current-theme.conf']:
            source=BACKUP/relative
            if source.exists(): shutil.copy2(source,CONFIG/relative)
        run([SB,'--reload'])
        print('Original SketchyBar and Kitty files restored. KiwiDesk live changes are separate.'); return
    action=args.action
    if action=='menu':
        selected=choose('Your appearance controls', ['Theme palette','Custom accent color','Wallpaper for this macOS desktop','Keep KiwiDesk colors'])
        action={'Theme palette':'theme','Custom accent color':'accent',
                'Wallpaper for this macOS desktop':'wallpaper','Keep KiwiDesk colors':'keep'}.get(selected)
    if action=='theme':
        selected=choose('Choose a shared palette',list(json.loads(PALETTES.read_text())))
        if selected: apply(selected)
    elif action=='accent':
        value=run(['/usr/bin/osascript','-e','set c to choose color\nreturn (item 1 of c as text) & "," & (item 2 of c as text) & "," & (item 3 of c as text)'])
        if value:
            accent='#'+''.join('{:02x}'.format(round(int(x)/257)) for x in value.split(','))
            apply(state().get('theme','Gruvbox'),accent)
    elif action=='keep':
        for path in ['border/focused_color','border/unfocused_color','pocket/color',
                     'space_bar/focused_item_color','space_bar/focused_highlight_color',
                     'kiwishelf/fill_color','kiwishelf/item_color','kiwishelf/active_item_color']:
            run([KD,'keep_settings','/settings/'+path])
        print('KiwiDesk theme colors kept.')
    elif action=='wallpaper':
        run([str(ROOT/'wallpaper')])

if __name__=='__main__':
    try: main()
    except (RuntimeError,ValueError,KeyError,OSError,subprocess.TimeoutExpired) as e:
        print(str(e),file=sys.stderr); sys.exit(1)
